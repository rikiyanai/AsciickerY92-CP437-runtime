extern "C" GlyphCoverageResult glyph_coverage_lookup(GlyphId gl) {
    GlyphCoverageResult r;
    if (glyph_id_is_sentinel(gl)) {
        r.coverage = 0;
        r.status = GLYPH_COV_STATUS_SENTINEL;
        return r;
    }
    if (glyph_id_is_legacy_cp437(gl)) {
        r.coverage = glyph_coverage_table[gl];
        r.status = GLYPH_COV_STATUS_LEGACY_CP437;
        return r;
    }
    r.coverage = 0;
    r.status = GLYPH_COV_STATUS_EXTENDED_UNBOUND;
    return r;
}

extern "C" GlyphCoverageResult glyph_coverage_lookup_with_manifest(GlyphId gl, const GlyphManifest* manifest)
{
    GlyphCoverageResult r;
    if (glyph_id_is_sentinel(gl)) {
        r.coverage = 0;
        r.status = GLYPH_COV_STATUS_SENTINEL;
        return r;
    }
    if (glyph_id_is_legacy_cp437(gl)) {
        r.coverage = glyph_coverage_table[gl];
        r.status = GLYPH_COV_STATUS_LEGACY_CP437;
        return r;
    }
    if (manifest && glyph_manifest_is_admitted(manifest, gl)) {
        uint16_t cov = 0;
        if (glyph_manifest_lookup_coverage(manifest, gl, &cov)) {
            r.coverage = cov;
            r.status = GLYPH_COV_STATUS_EXTENDED_ADMITTED;
            return r;
        }
    }
    r.coverage = 0;
    r.status = GLYPH_COV_STATUS_EXTENDED_UNBOUND;
    return r;
}
