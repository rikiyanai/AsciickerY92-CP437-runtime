void Game::LatchRemoteVisibilityIssue(uint64_t _stamp, bool* issue_seen_this_frame)
{
	debug.dbg_latched_last_remote_visibility_issue_stamp = _stamp;
	if (!issue_seen_this_frame || !*issue_seen_this_frame)
	{
		debug.dbg_latched_remote_visibility_issue_frames++;
		if (issue_seen_this_frame)
			*issue_seen_this_frame = true;
	}
}

