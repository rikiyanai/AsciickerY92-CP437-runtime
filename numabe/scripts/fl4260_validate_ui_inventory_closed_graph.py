#!/usr/bin/env python3
"""Validate the FL-4260 UI inventory closed graph.

Two layers of checking:

1. DEEP checks on the pinned FL-4548 controls (rows 429/432/672): their
   live leaves must carry the exact proof semantics (shade bands, light
   preconditions, bucket_state taxonomy, graph chain).
2. BROAD resolution gate over the FULL inventory (FL-4564 step-1 exit
   gate): every CSV row's `leaf_path` must resolve to a live leaf file
   at the fl4260/ root (never into the historical dated tree), and the
   generated INVENTORY_GRAPH.json index must agree with the CSV it was
   built from (same content hash, same row set). This makes a stale or
   partially-migrated graph fail closed instead of looking closed.

Field-level authoring completeness IS gated here: every non-tombstone,
proof-critical row must have zero MISSING proof-critical fields according to
INVENTORY_GRAPH.json. Tombstone rows (P5) and receipt-backed rows (P0) are
exempt from the zero-missing requirement in different ways: tombstones are
non-proof-critical by design; receipt-backed rows have live evidence. The graph
must also keep source_anchor_status consistent with dated_source_exists, and
control_uid must be the unique primary key (inventory_row is display-only and
may duplicate).
"""

from __future__ import annotations

import csv
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INV_ROOT = ROOT / "docs/research/ascii/verification/fl4260"
CSV_PATH = INV_ROOT / "CURRENT_UI_INVENTORY.csv"
PINS_PATH = INV_ROOT / "fl4548/initial_control_uids.json"
REQ_PATH = INV_ROOT / "fl4548/proof_evidence_requirements.md"
SCHEMA_PATH = INV_ROOT / "fl4548/proof_plan.schema.json"
ROOT_README_PATH = INV_ROOT / "README.md"
# FL-4512 paper claim ledger: §07.1.1 owns the id -> capture-instrument
# mapping (S1..S11). Leaves and plans cite instruments by those ids, so
# a cited id that the ledger does not define is a dangling reference.
LEDGER_PATH = ROOT / "docs/research/glyph-rendering/README.md"
TREE_PATH = INV_ROOT / "CURRENT_UI_INVENTORY_TREE.md"
FL4548_README_PATH = INV_ROOT / "fl4548/README.md"
# FL-4548 analyzer contract doc. Relocated 2026-07-19 from scripts/fl4548/README.md
# into the canonical docs tree (docs/agent/) during the loose-doc consolidation.
SCRIPT_README_PATH = ROOT / "docs/agent/fl4548_analyzers.md"
FAILURE_LOG_PATH = ROOT / "docs/FAILURE_LOG.md"
# Machine-readable closed-graph index generated by
# scripts/fl4260_generate_live_leaves.py (FL-4564 step 1).
GRAPH_PATH = INV_ROOT / "INVENTORY_GRAPH.json"
# FL-4564 evidence archive manifest: every dated dir must be classified.
MANIFEST_PATH = INV_ROOT / "EVIDENCE_ARCHIVE_MANIFEST.json"
# FL-4564 RQ/FL crosswalk: must exist and have zero dangling refs.
CROSSWALK_SCRIPT = ROOT / "scripts/fl_rq_crosswalk.py"
CROSSWALK_PATH = ROOT / "docs/RQ_FL_CROSSWALK.json"
# Historical browse tree: leaf_path values must NOT resolve into it.
DATED_ROOT = INV_ROOT / "2026-06-22-current-ui-inventory-tree"


REQUIRED = {
    "fl4260_row_429__material_selectable": {
        "tokens": [
            "CURRENT_UI_INVENTORY.csv row 429",
            "fl4548/initial_control_uids.json zero_delta_action",
            "FL-4548 / FL-4260 / RQ-201c",
            "ZERO final TERM++ cell deltas",
        ],
    },
    "fl4260_row_432__color_fg_r0": {
        "tokens": [
            "CURRENT_UI_INVENTORY.csv row 432",
            "fl4548/initial_control_uids.json selected_material_color_edit",
            "FL-4548 / FL-4260 / RQ-201c",
            "shade_max_exclusive=4",
            "visible headed setup",
            "SETUP_FAILURE",
            "bucket_state",
            "blocked_missing_fact",
        ],
    },
    "fl4260_target_672__mesh_material_id_edge_flow_controls": {
        "tokens": [
            "CURRENT_UI_INVENTORY.csv row 672",
            "headed before/action/after run bundle (none yet)",
            "SOURCE_IMPLEMENTED_LIVE_DIAGNOSTIC_PASS_GRAPH_CLOSURE_OPEN",
            "§03.1.4 U2/U7/U8",
            "471 predicted mesh:200 bundle cells",
            "zero unexpected cells",
        ],
    },
}

RECEIPT_REQUIRED = {
    "fl4260_row_429__material_selectable",
    "fl4260_row_432__color_fg_r0",
}


def fail(message: str) -> None:
    raise SystemExit(f"closed graph validation failed: {message}")


def load_rows() -> dict[str, dict[str, str]]:
    with CSV_PATH.open(newline="", encoding="utf-8") as handle:
        return {
            row["control_uid"]: row
            for row in csv.DictReader(handle)
            if row.get("control_uid")
        }


def main() -> None:
    rows = load_rows()
    pins = json.loads(PINS_PATH.read_text(encoding="utf-8"))
    pinned_uids = {
        pins["zero_delta_action"]["control_uid"],
        pins["selected_material_color_edit"]["control_uid"],
        pins["projected_mesh_feature_edit"]["control_uid"],
    }
    if pinned_uids != set(REQUIRED):
        fail(f"unexpected pinned controls: {sorted(pinned_uids)}")

    for uid, spec in REQUIRED.items():
        row = rows.get(uid)
        if row is None:
            fail(f"missing CSV row for {uid}")
        leaf_path = row.get("leaf_path") or ""
        if not leaf_path:
            fail(f"missing leaf_path for {uid}")
        live_leaf = INV_ROOT / leaf_path
        historical_leaf = INV_ROOT / "2026-06-22-current-ui-inventory-tree" / leaf_path
        if not live_leaf.exists():
            fail(f"live leaf does not exist for {uid}: {live_leaf}")
        if live_leaf.resolve() == historical_leaf.resolve():
            fail(f"live leaf points at historical tree for {uid}")
        text = live_leaf.read_text(encoding="utf-8")
        for token in [uid, *spec["tokens"]]:
            if token not in text:
                fail(f"{uid} leaf missing token: {token}")

    csv_text = CSV_PATH.read_text(encoding="utf-8")
    if "row band 0 (0..3 inclusive)" not in csv_text:
        fail("CSV row 432 does not record inclusive row-0 shade band")
    if "visible headed setup" not in csv_text:
        fail("CSV row 432 does not require a visible headed setup")

    req_text = REQ_PATH.read_text(encoding="utf-8")
    for token in [
        "Closed-Graph Inventory Contract",
        "CURRENT_UI_INVENTORY.csv",
        "live leaf",
        "shade_max_exclusive=4",
    ]:
        if token not in req_text:
            fail(f"proof evidence requirements missing token: {token}")

    schema_text = SCHEMA_PATH.read_text(encoding="utf-8")
    if "shade_max_exclusive=4" not in schema_text:
        fail("proof plan schema missing shade_max_exclusive=4 guidance")

    root_readme = ROOT_README_PATH.read_text(encoding="utf-8")
    for token in [
        "Status: PARTIAL / FL-4564 OPEN",
        "CURRENT_UI_INVENTORY.csv",
        "bucket_state",
        "Evidence Directory Policy",
        "Duplicate FL-4260",
        "full 321-row",
        "Remaining Original Audit Items",
        "EVIDENCE_ARCHIVE_MANIFEST.json",
        "End-to-end proof CI",
    ]:
        if token not in root_readme:
            fail(f"root inventory README missing token: {token}")

    tree_text = TREE_PATH.read_text(encoding="utf-8")
    for token in [
        "TOMBSTONED AS LIVE SURFACE",
        "TOMBSTONE:",
        "docs/research/ascii/verification/fl4260/README.md",
    ]:
        if token not in tree_text:
            fail(f"historical inventory tree missing tombstone token: {token}")

    fl4548_readme = FL4548_README_PATH.read_text(encoding="utf-8")
    for token in [
        "2026-07-07-r1-followup3",
        "RETAINED BACKEND-DRIVEN DIAGNOSTIC",
        "2026-07-07-r1-followup2",
        "RETAINED SETUP-FAILURE",
        "headed mouse and keyboard recipe",
        "receipt.json",
    ]:
        if token not in fl4548_readme:
            fail(f"FL-4548 harness README missing token: {token}")

    script_readme = SCRIPT_README_PATH.read_text(encoding="utf-8")
    for token in [
        "read-only predictors",
        "Backend-driven ASCIIID runners were physically deleted",
        "visible mouse click",
        "PROOF_OPEN",
    ]:
        if token not in script_readme:
            fail(f"script README missing token: {token}")

    # ---- Full-inventory resolution gate (FL-4564 step-1 exit gate) ----
    # Every row in the CSV, not just the pinned ones, must resolve to a
    # live leaf file directly under the fl4260/ root. A leaf that only
    # exists inside the dated 2026-06-22 browse tree does not count: the
    # closed-graph contract forbids using historical evidence as the
    # live proof surface.
    dated_resolved = str(DATED_ROOT.resolve())
    unresolved: list[str] = []
    for uid, row in rows.items():
        leaf_rel = (row.get("leaf_path") or "").strip()
        if not leaf_rel:
            unresolved.append(f"{uid}: empty leaf_path")
            continue
        leaf = INV_ROOT / leaf_rel
        if not leaf.is_file():
            unresolved.append(f"{uid}: no live leaf at {leaf_rel}")
            continue
        if str(leaf.resolve()).startswith(dated_resolved):
            unresolved.append(f"{uid}: leaf_path resolves into the historical dated tree")
    if unresolved:
        fail(
            f"{len(unresolved)}/{len(rows)} rows lack live leaves; "
            f"first offenders: {unresolved[:3]} "
            f"(regenerate with scripts/fl4260_generate_live_leaves.py)"
        )

    # The generated index must exist and must have been built from the
    # CSV as it is NOW. The generator stamps the CSV's sha256 into the
    # index, so any CSV edit without a regeneration run fails here
    # instead of leaving a silently stale graph.
    if not GRAPH_PATH.is_file():
        fail("INVENTORY_GRAPH.json missing (run scripts/fl4260_generate_live_leaves.py)")
    graph = json.loads(GRAPH_PATH.read_text(encoding="utf-8"))
    if graph.get("schema") != "fl4260.inventory_graph.v2":
        fail(f"unexpected INVENTORY_GRAPH.json schema: {graph.get('schema')}")
    csv_sha = hashlib.sha256(CSV_PATH.read_bytes()).hexdigest()
    if graph.get("source_csv_sha256") != csv_sha:
        fail("INVENTORY_GRAPH.json is stale: CSV changed since generation "
             "(rerun scripts/fl4260_generate_live_leaves.py)")
    graph_uids = {entry.get("control_uid") for entry in graph.get("rows", [])}
    if graph_uids != set(rows):
        fail("INVENTORY_GRAPH.json row set does not match CSV control_uids")
    # v2 proof-linkage checks: every pinned row must be receipt-backed
    # in the graph, their receipt files must exist, and the receipts must
    # actually hold PASS — the graph reads verdicts live at generation,
    # so a mismatch here means either a stale graph or a receipt edit.
    by_uid = {entry.get("control_uid"): entry for entry in graph.get("rows", [])}
    # Every leaf must state its proof position explicitly. A missing field is
    # not equivalent to PROOF_OPEN: it hides the difference between an
    # unproved leaf and a stale graph. Receipt metadata is forbidden on an
    # open leaf so a generated index cannot imply evidence that is not pinned.
    for uid, entry in by_uid.items():
        proof_status = entry.get("proof_status")
        if proof_status == "PROOF_OPEN":
            if any(entry.get(key) is not None for key in (
                "receipt_path", "last_verdict", "claim_ledger_ref"
            )):
                fail(f"graph row {uid} is PROOF_OPEN but carries receipt metadata")
            continue
        if not isinstance(proof_status, str) or not proof_status.startswith("RECEIPT_"):
            fail(f"graph row {uid} lacks explicit proof_status")
        if not entry.get("receipt_path") or not entry.get("last_verdict"):
            fail(f"graph row {uid} receipt status lacks pinned receipt metadata")
    for uid in RECEIPT_REQUIRED:
        entry = by_uid.get(uid, {})
        receipt_rel = entry.get("receipt_path")
        if not receipt_rel:
            fail(f"graph row {uid} lacks receipt_path (expected pinned receipt)")
        receipt_file = INV_ROOT / receipt_rel
        if not receipt_file.is_file():
            fail(f"graph row {uid} receipt file missing: {receipt_rel}")
        live_verdict = json.loads(
            receipt_file.read_text(encoding="utf-8")).get("verdict")
        if entry.get("last_verdict") != live_verdict:
            fail(f"graph row {uid} last_verdict={entry.get('last_verdict')} "
                 f"but receipt says {live_verdict} (regenerate the graph)")
        if live_verdict != "PASS":
            fail(f"pinned receipt for {uid} is not PASS: {live_verdict}")
        if not entry.get("claim_ledger_ref"):
            fail(f"graph row {uid} lacks claim_ledger_ref")
        if entry.get("source_anchor_status") != "AUTHORED_FILE_LINE":
            fail(f"graph row {uid} source_anchor_status is "
                 f"{entry.get('source_anchor_status')}, expected AUTHORED_FILE_LINE")

    # ---- capture-instrument linkage (re-audit item 5, FL-4564) ----
    # Proof leaves and plans cite capture instruments by ledger id (S1..
    # S11). The mapping from id to concrete mechanism is owned by ONE
    # place: paper ledger §07.1.1. This check makes the citation
    # mechanical: the section must exist, the ids the R1 surfaces rely
    # on must be defined there, every id cited in an R1 leaf or current
    # plan must resolve to a ledger row, and the leaves must name the
    # ledger section so a reader can follow the edge without tribal
    # knowledge.
    ledger_text = LEDGER_PATH.read_text(encoding="utf-8")
    if "### §07.1.1" not in ledger_text:
        fail("paper ledger missing the §07.1.1 capture-instrument section")
    # Instrument rows look like "| S2 | atomic frame + cell records | ..."
    ledger_ids = set(re.findall(r"^\| (S\d+) \|", ledger_text, flags=re.MULTILINE))
    required_ids = {"S2", "S4", "S5", "S10", "S11"}
    if not required_ids <= ledger_ids:
        fail("ledger §07.1.1 does not define the R1 capture instruments; "
             f"found only {sorted(ledger_ids)}")
    followup3 = INV_ROOT / "fl4548/2026-07-07-r1-followup3"
    citing = [INV_ROOT / rows[uid]["leaf_path"] for uid in REQUIRED]
    citing += [followup3 / "plan429.json", followup3 / "plan432.json"]
    for path in citing:
        text = path.read_text(encoding="utf-8")
        # Any S<number> token is treated as an instrument citation; an id
        # the ledger does not define is a dangling reference and fails.
        cited = set(re.findall(r"\bS\d{1,2}\b", text))
        if not cited:
            fail(f"{path.name} cites no capture instrument ids (S2 etc.)")
        dangling = sorted(cited - ledger_ids)
        if dangling:
            fail(f"{path.name} cites instrument ids missing from ledger "
                 f"§07.1.1: {dangling}")
    for uid in REQUIRED:
        leaf_text = (INV_ROOT / rows[uid]["leaf_path"]).read_text(encoding="utf-8")
        if "§07.1.1" not in leaf_text:
            fail(f"{uid} leaf does not name the ledger instrument section §07.1.1")

    failure_log = FAILURE_LOG_PATH.read_text(encoding="utf-8")
    fl4260_headers = [
        line for line in failure_log.splitlines() if line.startswith("### FL-4260:")
    ]
    if len(fl4260_headers) != 1:
        fail(f"expected exactly one FL-4260 narrative header, found {len(fl4260_headers)}")
    # After the FL-4564 duplicate-header cleanup, no FL header ID may appear more
    # than once in the failure log; known duplicates were renumbered to FL-4568,
    # FL-4569, and FL-4570.
    header_ids = [line.split(":")[0].strip() for line in fl4260_headers]
    # This is just the FL-4260 set; the broader duplicate check lives in
    # analyze_failure_log.py validate.
    for token in [
        "ASCIIID Material Look authoring surface remains open",
        "ASCIIID Editor UI/UX Audit Fixes",
        "ASCIID proof inventory surfaces are not closed graph",
    ]:
        if token not in failure_log:
            fail(f"failure log missing known process token: {token}")

    # ---- Field-level authoring completeness gate (FL-4564 step-2 exit) ----
    # Non-tombstone, proof-critical rows must have no MISSING proof-critical
    # fields. Receipt-backed rows are already proven; tombstones are explicitly
    # non-proof-critical; all other rows must be fully authored.
    incomplete: list[str] = []
    inconsistent: list[str] = []
    for entry in graph.get("rows", []):
        uid = entry.get("control_uid")
        priority = entry.get("authoring_priority")
        missing = entry.get("missing_fields", [])
        dated_exists = entry.get("dated_source_exists")
        anchor_status = entry.get("source_anchor_status")
        if priority == "P5_TOMBSTONE_DECISION":
            continue
        if priority != "P0_RECEIPT_BACKED" and missing:
            incomplete.append(f"{uid} ({priority}): {missing}")
        # source_anchor_status must not be MISSING for non-tombstone rows
        # (even P1 rows without a dated source can carry authored file:line
        # anchors in their leaf text).
        if priority != "P5_TOMBSTONE_DECISION" and anchor_status == "MISSING":
            incomplete.append(f"{uid} ({priority}): source_anchor_status=MISSING")
        # Consistency: a row cannot claim a dated-tree anchor if no dated source exists.
        if not dated_exists and anchor_status == "FROM_DATED_TREE":
            inconsistent.append(
                f"{uid}: dated_source_exists=False but source_anchor_status=FROM_DATED_TREE")
    if incomplete:
        fail(f"{len(incomplete)} proof-critical rows still have MISSING fields; "
             f"first: {incomplete[:3]}")
    if inconsistent:
        fail(f"{len(inconsistent)} rows have inconsistent dated_source_exists/"
             f"source_anchor_status; first: {inconsistent[:3]}")

    # control_uid must be unique (inventory_row is display-only and may duplicate).
    seen_uids: set[str] = set()
    dup_uids: list[str] = []
    for entry in graph.get("rows", []):
        uid = entry.get("control_uid")
        if uid in seen_uids:
            dup_uids.append(uid)
        seen_uids.add(uid)
    if dup_uids:
        fail(f"duplicate control_uids in graph: {sorted(set(dup_uids))}")

    # FL-4564 evidence-archive coverage gate.
    check_evidence_archive_manifest()

    # FL-4564 RQ/FL crosswalk coverage gate.
    check_rq_fl_crosswalk()

    # Report both layers so a passing run states what was actually checked (FL-4564).
    print(f"fl4260 closed graph ok (FL-4564): {len(rows)}/{len(rows)} rows resolve to live leaves; "
          "INVENTORY_GRAPH.json consistent; R1 pinned deep checks pass; "
          f"zero MISSING for {len(rows)-9-2} non-tombstone proof-critical rows")




def check_evidence_archive_manifest() -> None:
    """FL-4564: every dated evidence directory under fl4260/ is classified."""
    if not MANIFEST_PATH.is_file():
        fail("EVIDENCE_ARCHIVE_MANIFEST.json missing")
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    if manifest.get("schema") not in {"fl4260.evidence_archive_manifest.v1", "fl4260.evidence_archive_manifest.v2"}:
        fail(f"unexpected manifest schema: {manifest.get('schema')}")
    classified = manifest.get("classifications", {})
    dated_dirs = sorted(
        str(p.relative_to(INV_ROOT))
        for p in INV_ROOT.rglob("2026-*")
        if p.is_dir()
    )
    unclassified = [d for d in dated_dirs if d not in classified]
    if unclassified:
        fail(f"{len(unclassified)} dated dirs not in manifest: {unclassified[:3]}")
    unknown = [d for d, v in classified.items() if v.get("classification") not in {
        "current_referenced", "historical_retained", "tombstone_candidate"
    }]
    if unknown:
        fail(f"manifest contains unknown classifications: {unknown[:3]}")
    summary = manifest.get("summary", {})
    print(f"evidence archive manifest ok (FL-4564): {len(dated_dirs)} dated dirs classified; "
          f"current_referenced={summary.get('current_referenced', 0)}, "
          f"historical_retained={summary.get('historical_retained', 0)}, "
          f"tombstone_candidate={summary.get('tombstone_candidate', 0)}")



def check_rq_fl_crosswalk() -> None:
    """FL-4564: RQ/FL crosswalk must be current and have zero dangling refs."""
    if not CROSSWALK_SCRIPT.is_file():
        fail("scripts/fl_rq_crosswalk.py missing")
    result = subprocess.run(
        [sys.executable, str(CROSSWALK_SCRIPT)],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail(f"fl_rq_crosswalk.py reported dangling refs or errors: stdout={result.stdout!r} stderr={result.stderr!r}")
    if not CROSSWALK_PATH.is_file():
        fail("docs/RQ_FL_CROSSWALK.json missing after generator run")
    crosswalk = json.loads(CROSSWALK_PATH.read_text(encoding="utf-8"))
    summary = crosswalk.get("summary", {})
    drq = summary.get("dangling_rq_refs", -1)
    dfl = summary.get("dangling_fl_refs", -1)
    if drq != 0 or dfl != 0:
        fail(f"RQ/FL crosswalk has dangling refs: dangling_rq={drq}, dangling_fl={dfl}")
    print(f"rq/fl crosswalk ok (FL-4564): {summary.get('rq_rows')} RQ rows, "
          f"{summary.get('fl_overlay_entries')} FL entries, "
          f"{summary.get('fl_to_rq_edges')} FL->RQ edges, "
          f"{summary.get('rq_to_fl_edges')} RQ-<FL edges, zero dangling")

if __name__ == "__main__":
    main()
