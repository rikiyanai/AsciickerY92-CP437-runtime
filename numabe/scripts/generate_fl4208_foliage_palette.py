#!/usr/bin/env python3
"""Generate FL-4208 foliage palette shader tables from JSON authority."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCHEMA = ROOT / "assets/glyphs/fixtures/fl4208_foliage_palette_schema_v1.json"
DEFAULT_PALETTE = ROOT / "assets/glyphs/fixtures/fl4208_foliage_palette_v1.json"
DEFAULT_RECEIPTS = ROOT / "assets/glyphs/generated/fl4208_role_scoring.jsonl"
DEFAULT_GLSL = ROOT / "godot_project/shaders/generated/fl4208_foliage_palette.generated.glsl"
DEFAULT_MANIFEST = ROOT / "assets/glyphs/generated/fl4208_foliage_palette_manifest.json"
# FL-4208 (ADR "material-owned") inline-shader sync: Godot RD compute shaders have no
# `#include`, so the generated palette table is inlined into ascii_compositor.glsl
# between the FL4208_FOLIAGE_PALETTE_BEGIN / FL4208_FOLIAGE_PALETTE_END markers. The
# generator owns both copies; the standalone .generated.glsl file remains the canonical
# audit artifact and the inlined block in the compositor is what the runtime actually
# executes. `--check` validates both are in sync with the JSON source-of-truth.
DEFAULT_SHADER_INLINE = ROOT / "godot_project/render/ascii/raster/ascii_compositor.glsl"
SHADER_INLINE_BEGIN = "// FL4208_FOLIAGE_PALETTE_BEGIN"
SHADER_INLINE_END = "// FL4208_FOLIAGE_PALETTE_END"

ROLE_IDS = {
    "stem": 0,
    "tip": 1,
    "leaf_left": 2,
    "leaf_right": 3,
    "flower": 4,
    "accent": 5,
}

DENSITY_IDS = {
    "sparse": 0,
    "medium": 1,
    "dense": 2,
}

DIRECTION_IDS = {
    "neutral": 0,
    "left": 1,
    "right": 2,
    "vertical": 3,
}

CONVEXITY_IDS = {
    "flat": 0,
    "outward": 1,
    "inward": 2,
}

TERMINAL_IDS = {
    "simple": 0,
    "split": 1,
    "branch": 2,
    "voided": 3,
}

STATUS_IDS = {
    "accepted": 0,
    "rejected_leaf_left_wrong_direction": 1,
    "rejected_leaf_right_wrong_direction": 2,
    "rejected_flower_medium_neutral": 3,
    "rejected_flower_dense_neutral": 4,
    "rejected_accent_as_default_flower_head": 5,
    # FL-4208 step #11: two additional rejection rows landed in the
    # palette ("Add rejected rows for known invalid combos"). The
    # generator picks up their numeric IDs here; the shader rejected_row
    # consumers can fail closed on the matching integer value.
    "rejected_emoji_presentation_codepoint": 6,
    "rejected_script_prescreen_without_receipt": 7,
}


# FL-4208 step #28: blade hash lane. A deterministic 4-lane mapping
# derived from palette_entry_id so blade-variant selection has a
# stable per-row lane without requiring a runtime hash. Matches the
# plan's "blade hash lane" axis on the generated palette table.
BLADE_HASH_LANE_COUNT = 4


def blade_hash_lane(palette_entry_id: int) -> int:
    return int(palette_entry_id) % BLADE_HASH_LANE_COUNT


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def dump_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(obj, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT))


def i(value: Any) -> int:
    return int(value)


def row_tuple(row: dict[str, Any]) -> str:
    return (
        "Fl4208FoliagePaletteRow("
        f"{i(row['palette_entry_id'])}, "
        f"{i(row['glyph_id'])}, "
        f"{i(row['fallback_baseline_id'])}, "
        f"{ROLE_IDS[row['role']]}, "
        f"{DENSITY_IDS[row['density_bucket']]}, "
        f"{DIRECTION_IDS[row['direction_bucket']]}, "
        f"{CONVEXITY_IDS[row['convexity_bucket']]}, "
        f"{TERMINAL_IDS[row['terminal_shape']]}, "
        f"{1 if row['accent_allowed'] else 0}, "
        f"{1 if row['default_head_allowed'] else 0}, "
        f"{1 if row['candidate_receipt_required'] else 0}, "
        f"{STATUS_IDS[row['rejected_combo_status']]}, "
        f"{blade_hash_lane(int(row['palette_entry_id']))}"
        ")"
    )


def build_outputs(schema_path: Path, palette_path: Path, receipts_path: Path) -> tuple[str, dict[str, Any]]:
    palette_doc = load_json(palette_path)
    rows = sorted(palette_doc["palette"], key=lambda row: int(row["palette_entry_id"]))
    accepted = [row for row in rows if row["rejected_combo_status"] == "accepted"]
    rejected = [row for row in rows if row["rejected_combo_status"] != "accepted"]
    lines = [
        "// Generated by scripts/generate_fl4208_foliage_palette.py. Do not edit by hand.",
        "// Source: assets/glyphs/fixtures/fl4208_foliage_palette_v1.json",
        "// FL-4208 step #28: deterministic palette table. Rows are sorted by",
        "// palette_entry_id. Each row exposes the keyed-by axes (role,",
        "// density_bucket, direction_bucket, convexity_bucket, terminal_shape,",
        "// blade_hash_lane) so the shader can index the array by any axis tuple",
        "// without a runtime hash. Stale-hash validation lives only in",
        "// scripts/generate_fl4208_foliage_palette.py --check after the",
        "// stale FL-4208 validator proof owner was deleted.",
        "",
        "struct Fl4208FoliagePaletteRow {",
        "\tint palette_entry_id;",
        "\tint glyph_id;",
        "\tint fallback_baseline_id;",
        "\tint role;",
        "\tint density_bucket;",
        "\tint direction_bucket;",
        "\tint convexity_bucket;",
        "\tint terminal_shape;",
        "\tint accent_allowed;",
        "\tint default_head_allowed;",
        "\tint candidate_receipt_required;",
        "\tint rejected_combo_status;",
        "\tint blade_hash_lane;",
        "};",
        "",
        f"const int FL4208_FOLIAGE_PALETTE_ROW_COUNT = {len(rows)};",
        f"const int FL4208_FOLIAGE_PALETTE_ACCEPTED_ROW_COUNT = {len(accepted)};",
        f"const int FL4208_FOLIAGE_PALETTE_REJECTED_ROW_COUNT = {len(rejected)};",
        "",
        f"const Fl4208FoliagePaletteRow FL4208_FOLIAGE_PALETTE_ROWS[{len(rows)}] = Fl4208FoliagePaletteRow[{len(rows)}](",
    ]
    for idx, row in enumerate(rows):
        comma = "," if idx + 1 < len(rows) else ""
        lines.append(f"\t{row_tuple(row)}{comma}")
    lines.extend([
        ");",
        "",
    ])
    glsl = "\n".join(lines)
    manifest = {
        "accepted_row_count": len(accepted),
        "generated_at": date.today().isoformat(),
        "generator": "scripts/generate_fl4208_foliage_palette.py",
        "max_palette_entry_id": max(int(row["palette_entry_id"]) for row in rows),
        "palette": rel(palette_path),
        "palette_sha256": sha256_file(palette_path),
        "rejected_row_count": len(rejected),
        "schema": rel(schema_path),
        "schema_sha256": sha256_file(schema_path),
        "schema_version": 1,
        "shader_output": rel(DEFAULT_GLSL),
        "shader_sha256": sha256_bytes(glsl.encode("utf-8")),
        "total_row_count": len(rows),
    }
    return glsl, manifest


def build_shader_inline_block(glsl: str) -> str:
    """Return the body the shader inline block must contain between BEGIN / END markers.

    The standalone .generated.glsl file carries a generator-warning header; the inline
    block carries the same struct + ROW_COUNT consts + array literal but skips the
    "Generated by ..." preamble lines because the BEGIN marker line in the compositor
    already documents the sync contract. Keeping these two views aligned is what
    `--check` enforces.
    """
    body_lines: list[str] = []
    skip_header = True
    for line in glsl.splitlines():
        if skip_header:
            if line.startswith("struct Fl4208FoliagePaletteRow"):
                skip_header = False
            else:
                continue
        body_lines.append(line)
    while body_lines and body_lines[-1] == "":
        body_lines.pop()
    return "\n".join(body_lines)


def render_shader_inline_block(glsl: str) -> str:
    body = build_shader_inline_block(glsl)
    return (
        f"{SHADER_INLINE_BEGIN} — managed by scripts/generate_fl4208_foliage_palette.py\n"
        "// This block is synced from godot_project/shaders/generated/fl4208_foliage_palette.generated.glsl.\n"
        "// Source of truth: assets/glyphs/fixtures/fl4208_foliage_palette_v1.json.\n"
        "// Do not edit by hand. Regenerate with `python3 scripts/generate_fl4208_foliage_palette.py`\n"
        "// (validated by `--check`). The palette table is the FL-4208 ADR \"material-owned\"\n"
        "// selector consumed by foliage_glyph_for_coverage() below — it replaces the prior\n"
        "// inline int[N] arrays so glyph choice is a morphology+role lookup, not a hardcoded\n"
        "// constant. The FOLIAGE_DIR_ / FOLIAGE_CONVEX_ / FOLIAGE_TERMINAL_ / FOLIAGE_ROLE_ /\n"
        "// FOLIAGE_DENSITY_ constants are declared above. Rejected rows (rejected_combo_status != 0)\n"
        "// must be skipped by the selector; they are kept in the table so audit tooling can\n"
        "// confirm the rejection chain. glyph_id == -1 means the row is informational only.\n"
        f"{body}\n"
        f"{SHADER_INLINE_END}"
    )


def find_inline_markers(text: str) -> tuple[int, int] | None:
    begin = text.find(SHADER_INLINE_BEGIN)
    end = text.find(SHADER_INLINE_END)
    if begin == -1 or end == -1 or end < begin:
        return None
    end_eol = text.find("\n", end)
    if end_eol == -1:
        end_eol = len(text)
    return (begin, end_eol)


def replace_shader_inline_block(text: str, new_block: str) -> str:
    span = find_inline_markers(text)
    if span is None:
        raise RuntimeError(
            f"missing inline markers {SHADER_INLINE_BEGIN!r} / {SHADER_INLINE_END!r}; "
            "add them around the existing palette block before re-running this script."
        )
    begin, end = span
    return text[:begin] + new_block + text[end:]


def write_outputs(
    glsl_path: Path,
    manifest_path: Path,
    glsl: str,
    manifest: dict[str, Any],
    inline_path: Path | None,
) -> None:
    glsl_path.parent.mkdir(parents=True, exist_ok=True)
    glsl_path.write_text(glsl, encoding="utf-8")
    dump_json(manifest_path, manifest)
    if inline_path is not None and inline_path.is_file():
        current = inline_path.read_text(encoding="utf-8")
        updated = replace_shader_inline_block(current, render_shader_inline_block(glsl))
        if updated != current:
            inline_path.write_text(updated, encoding="utf-8")


def check_outputs(
    glsl_path: Path,
    manifest_path: Path,
    glsl: str,
    manifest: dict[str, Any],
    inline_path: Path | None,
) -> int:
    errors: list[str] = []
    if not glsl_path.is_file():
        errors.append(f"missing generated shader: {rel(glsl_path)}")
    elif glsl_path.read_text(encoding="utf-8") != glsl:
        errors.append(f"stale generated shader: {rel(glsl_path)}")
    if not manifest_path.is_file():
        errors.append(f"missing manifest: {rel(manifest_path)}")
    else:
        current = load_json(manifest_path)
        if current != manifest:
            errors.append(f"stale manifest: {rel(manifest_path)}")
    if inline_path is not None and inline_path.is_file():
        current_text = inline_path.read_text(encoding="utf-8")
        span = find_inline_markers(current_text)
        if span is None:
            errors.append(f"missing inline markers in: {rel(inline_path)}")
        else:
            begin, end = span
            actual_block = current_text[begin:end]
            expected_block = render_shader_inline_block(glsl)
            if actual_block != expected_block:
                errors.append(f"stale inline palette block in: {rel(inline_path)}")
    if errors:
        for error in errors:
            print(f"FAIL: {error}", file=sys.stderr)
        return 1
    print("FL4208_FOLIAGE_PALETTE_CODEGEN_CHECK_OK")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--palette", type=Path, default=DEFAULT_PALETTE)
    parser.add_argument("--receipts", type=Path, default=DEFAULT_RECEIPTS)
    parser.add_argument("--out-glsl", type=Path, default=DEFAULT_GLSL)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument(
        "--shader-inline",
        type=Path,
        default=DEFAULT_SHADER_INLINE,
        help=(
            "Path to ascii_compositor.glsl whose FL4208_FOLIAGE_PALETTE_BEGIN/END "
            "block is kept in sync with the generated table. Pass an empty string "
            "to skip inline-sync."
        ),
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    inline_path: Path | None
    if args.shader_inline is None or str(args.shader_inline) == "":
        inline_path = None
    else:
        inline_path = args.shader_inline

    glsl, manifest = build_outputs(args.schema, args.palette, args.receipts)
    if args.check:
        return check_outputs(args.out_glsl, args.manifest, glsl, manifest, inline_path)
    write_outputs(args.out_glsl, args.manifest, glsl, manifest, inline_path)
    print("FL4208_FOLIAGE_PALETTE_CODEGEN_WRITE_OK")
    print(f"shader={rel(args.out_glsl)}")
    print(f"manifest={rel(args.manifest)}")
    if inline_path is not None and inline_path.is_file():
        print(f"shader_inline={rel(inline_path)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
