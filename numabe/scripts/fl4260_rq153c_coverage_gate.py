#!/usr/bin/env python3
"""FL-4260 RQ-153c full referenced-GID coverage gate (named producer).

RQ-153c requires that AFTER the thin headed terrain slice proves PROFILE
consumption can work (RQ-154), the FULL referenced set of profile-cell candidate
GIDs is renderability-screened, rendered into atlas pages, measured with
shape-catalog rows, candidate-floor enforced, and that zero-coverage plus
unrenderable results are fed into the SAME coverage gate. The referenced set is
the union of candidate/primary GIDs cited by every cell of
``material.morphology.v2.profile_tables.json``.

That referenced set is DERIVED from the generated tables on every run (FL-4260).
It is not a constant, and this gate asserts no particular value for it. The
tables are regenerated whenever the catalogue changes and the set moves with
them: an earlier revision of this file recorded "canon: 473 unique, 332 above
the ceiling, max 1691", while the current tables yield 500 unique, 359 above the
ceiling 671, max 1875. Those figures are OBSERVATIONS reported by the inventory
gate, not thresholds to be met; writing them into canon is what made a moving
measurement look frozen.

This script is that coverage gate. It is a POST-RUN QUERY over already-generated
artifacts (Law 13: analyzer gates own proof). It mutates nothing.

What it proves (mechanical, fail-closed — any miss FAILS the gate):
  rq153c_referenced_gid_inventory          referenced set extracted, 332 above 671
  rq153c_full_referenced_gid_atlas_coverage every referenced GID present in the
                                            v2 atlas glyph_index (zero-coverage
                                            list MUST be empty)
  rq153c_renderability_receipts            every referenced GID has a shape
                                            receipt carrying rendered_bitmap_sha256
                                            (unrenderable list MUST be empty)
  rq153c_shape_catalog_measurement_rows    every referenced GID has a v2 shape
                                            catalog measurement row (shape6_norm
                                            length 6)
  rq153c_candidate_floor                   every COMMON (non-rare) cell carries at
                                            least its declared min_candidate_count
                                            (>= 8) candidates
  rq153c_profile_marker_contract           the runtime fail-marker identity is
                                            backed by a GENERATED receipt taken
                                            from the engine's own producer
  rq153c_runtime_accepts_input             the running product took a movement
                                            input and a camera turn and CHANGED
                                            what it drew (fail-closed: no
                                            receipt means no evidence the
                                            product runs -- FL-4665)

IMPORTANT: gates 1-6 are all queries over files on disk. Every one of them can
be green while the editor is frozen and its controls do nothing, because none of
them ever starts the product. That is not a hypothetical: on 2026-08-03 this
gate reported mechanical coverage PASS while the operator had a frozen ASCIIID
editor / TERM++ surface in front of them. Gate 7 exists so that state can no
longer be reported as PASS.

What it does NOT do (operator residual — never set here, Law 16):
  rq153c_manual_review_acceptance          per-cell human accept of the primary
                                            winner. Reported as an OBSERVATION.
                                            Review-ready status waits for the
                                            operator manual-review pass. The
                                            mechanical gate passing is NOT closure.

Exit codes:
  0  mechanical coverage verdict PASS
  2  mechanical coverage verdict FAIL (any fail-closed check missed)
  3  required input artifact missing
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
GEN = REPO_ROOT / "assets/glyphs/generated"
PROFILE_TABLES = GEN / "material.morphology.v2.profile_tables.json"
V2_ATLAS = REPO_ROOT / "assets/glyphs/atlases/material.morphology.v2.atlas_of_atlases.json"
V2_SHAPE_CATALOG = GEN / "material.morphology.v2.shape_catalog.json"
SHAPE_RECEIPTS = GEN / "material.morphology.v2.shape_receipts.jsonl"
MANUAL_RECEIPTS = GEN / "material.morphology.v2.manual_review_receipts.jsonl"
# The runtime fail-marker receipt. This is GENERATED by
# scripts/generate_fl4131_profile_marker_contract.py, which compiles the engine
# and calls Fl4131ProfileMarkerProducer directly, so it is a measurement of the
# renderer rather than a description of it.
#
# It replaces a hand-written document that used to live under
# docs/research/ascii/verification/fl4260/. That document was a person's claim
# about the runtime, it could drift from the engine unnoticed, and it was in
# fact deleted -- which left this gate failing on a missing file instead of
# reporting anything about marker behaviour (FL-4260).
MARKER_CONTRACT = GEN / "fl4131.profile_marker_contract.v1.json"

# The marker classes the engine must define. A marker is what the renderer draws
# when it cannot honestly draw a real glyph, so all three must be present.
REQUIRED_MARKER_CLASSES = (
    "FL4131_MARKER_MISSING_POLICY",
    "FL4131_MARKER_MISSING_GLYPH",
    "FL4131_MARKER_DIAGNOSTIC",
)

# ---------------------------------------------------------------------------
# RUNTIME INTERACTION RECEIPT  (FL-4260, FL-4665)
# ---------------------------------------------------------------------------
# Everything else this gate measures is a POST-RUN QUERY over files on disk:
# which glyph ids the tables cite, whether those glyphs are in the atlas,
# whether they were measured, what the marker producer returns. Every one of
# those can be green while the product itself does not run at all.
#
# That is not hypothetical. On 2026-08-03 the operator reported the ASCIIID
# editor / TERM++ surface frozen with controls dead, while this gate reported
# mechanical coverage PASS. The gate was answering a question nobody asked.
#
# So the gate now REQUIRES evidence that the running product accepted input and
# changed what it drew: a movement input and a camera turn, each producing
# frames that differ from the frame before them, captured in one continuous run
# of a named build. A single still cannot show this -- a frozen program emits a
# perfectly valid still forever.
#
# There is deliberately NO default-pass. If the receipt is absent, stale, or
# records frames that did not change, this gate FAILS and takes the mechanical
# verdict down with it. Absence of evidence that the product runs is treated as
# evidence that it does not.
RUNTIME_INTERACTION_RECEIPT = (
    REPO_ROOT / "docs/research/ascii/verification/fl4260/runtime_interaction/"
                "fl4260_runtime_interaction.v1.json")

# The engine binary whose behaviour a receipt would be describing. A receipt
# that names a different build than the one on disk is stale by definition.
ENGINE_SOURCES_FOR_INTERACTION = (
    REPO_ROOT / "engine/fl4131_runtime_harri_resolver.cpp",
    REPO_ROOT / "platform/terminal_gl_present.cpp",
)

V1_FROZEN_CEILING = 671  # GIDs <= this are the additive.v1 frozen range; above is v2 expansion


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if not path.exists():
        return rows
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def collect_referenced(tables: dict[str, Any]) -> tuple[set[int], dict[str, list[dict[str, Any]]]]:
    """Return (referenced GID set, cells grouped by common/rare).

    A cell is COMMON unless it carries rare_cell:true. Candidate-floor only
    applies to common cells (canon: rare lanes may legitimately be thinner).
    """
    referenced: set[int] = set()
    cells = {"common": [], "rare": []}
    for profile, lane_table in tables.get("profiles", {}).items():
        for direction, density_cells in lane_table.items():
            for density, cell in density_cells.items():
                if not isinstance(cell, dict):
                    continue
                for gid in cell.get("candidate_glyph_ids", []):
                    try:
                        referenced.add(int(gid))
                    except (TypeError, ValueError):
                        pass
                for gid in cell.get("primary_glyph_ids", []):
                    try:
                        referenced.add(int(gid))
                    except (TypeError, ValueError):
                        pass
                bucket = "rare" if cell.get("rare_cell") else "common"
                cells[bucket].append(
                    {
                        "key": f"{profile}/{direction}/{density}",
                        "candidate_count": len(cell.get("candidate_glyph_ids", [])),
                        "min_candidate_count": int(cell.get("min_candidate_count", 8)),
                        "primary_glyph_ids": [int(g) for g in cell.get("primary_glyph_ids", []) if isinstance(g, int)],
                    }
                )
    return referenced, cells


def check_runtime_interaction() -> dict[str, Any]:
    """Does the running product accept input and change what it draws?

    Returns a gate dict with a ``pass`` key. There is no path through this
    function that returns ``pass: True`` without a receipt on disk describing a
    real run, because the failure this guards against is precisely a green
    report standing in for a product that does not run.

    What a valid receipt must show:

      * a MOVEMENT input and a CAMERA TURN input were delivered to the product;
      * each produced a frame whose content differs from the frame before it --
        a frozen program keeps emitting a valid-looking still, so identical
        frames are the signature of the failure, not of stability;
      * all frames came from ONE continuous run, so two unrelated screenshots
        cannot be stitched into a false motion claim;
      * the run used the engine sources currently on disk.

    FL-4665 owns the headed freeze. Its card currently reads
    ``resolved-accounted`` while the surface is frozen, so this gate does not
    consult FL status either -- only evidence from a run.
    """
    detail: dict[str, Any] = {
        "receipt": str(RUNTIME_INTERACTION_RECEIPT.relative_to(REPO_ROOT)),
        "exists": RUNTIME_INTERACTION_RECEIPT.exists(),
        "fail_closed": True,
        "owning_fl": "FL-4665 (headed freeze), FL-4260 (this gate)",
    }

    if not RUNTIME_INTERACTION_RECEIPT.exists():
        detail["reason"] = (
            "No runtime-interaction receipt exists, so there is no evidence the "
            "product runs at all. Every other gate here is a query over files on "
            "disk and stays green while the editor is frozen. Treating that as "
            "PASS is what this gate exists to stop."
        )
        detail["observed_2026_08_03"] = (
            "operator reported ASCIIID editor / TERM++ frozen with controls "
            "non-functional while this gate reported mechanical coverage PASS"
        )
        detail["to_satisfy"] = (
            "capture one continuous run that delivers a movement input and a "
            "camera turn, recording per-input frame hashes that differ from the "
            "preceding frame, plus the engine source hashes used"
        )
        return {"pass": False, **detail}

    receipt = load_json(RUNTIME_INTERACTION_RECEIPT)

    # The receipt must describe the engine that is actually on disk. A receipt
    # taken against different sources says nothing about the current build.
    expected_sources = {
        str(path.relative_to(REPO_ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in ENGINE_SOURCES_FOR_INTERACTION if path.exists()
    }
    recorded_sources = receipt.get("engine_sources", {})
    sources_current = recorded_sources == expected_sources

    # Both input kinds must be present, and each must have moved the picture.
    inputs = receipt.get("inputs", [])
    by_kind = {entry.get("kind"): entry for entry in inputs if isinstance(entry, dict)}
    required_kinds = ("movement", "camera_turn")

    kinds_present = all(kind in by_kind for kind in required_kinds)
    frames_changed = all(
        by_kind.get(kind, {}).get("frame_sha256_before")
        not in (None, by_kind.get(kind, {}).get("frame_sha256_after"))
        for kind in required_kinds
    )

    # One continuous run: every input must carry the same run identifier.
    run_ids = {entry.get("run_id") for entry in inputs if isinstance(entry, dict)}
    single_run = len(run_ids) == 1 and None not in run_ids

    passed = bool(kinds_present and frames_changed and single_run and sources_current)

    detail.update({
        "input_kinds_recorded": sorted(by_kind),
        "both_required_inputs_present": kinds_present,
        "each_input_changed_the_frame": frames_changed,
        "single_continuous_run": single_run,
        "engine_sources_current": sources_current,
        "run_ids": sorted(str(r) for r in run_ids),
    })
    if not sources_current:
        detail["stale_sources"] = {
            "recorded": recorded_sources,
            "on_disk": expected_sources,
        }
    return {"pass": passed, **detail}


def run_gate() -> tuple[dict[str, Any], int]:
    missing = [p.name for p in (PROFILE_TABLES, V2_ATLAS, V2_SHAPE_CATALOG, SHAPE_RECEIPTS) if not p.exists()]
    if missing:
        return {"verdict": "INPUT_MISSING", "missing": missing}, 3

    tables = load_json(PROFILE_TABLES)
    atlas = load_json(V2_ATLAS)
    catalog = load_json(V2_SHAPE_CATALOG)
    receipts = load_jsonl(SHAPE_RECEIPTS)

    referenced, cells = collect_referenced(tables)
    above = sorted(g for g in referenced if g > V1_FROZEN_CEILING)

    atlas_gids = {int(k) for k in atlas.get("glyph_index", {}).keys() if str(k).lstrip("-").isdigit()}
    cat_by_gid = {int(e["glyph_id"]): e for e in catalog.get("entries", []) if "glyph_id" in e}
    rec_by_gid = {int(r["glyph_id"]): r for r in receipts if "glyph_id" in r}

    gates: dict[str, dict[str, Any]] = {}

    # 1. referenced GID inventory
    gates["rq153c_referenced_gid_inventory"] = {
        "pass": len(referenced) > 0 and len(above) > 0,
        "referenced_total": len(referenced),
        "referenced_above_ceiling": len(above),
        "ceiling": V1_FROZEN_CEILING,
        "max_gid": max(referenced) if referenced else None,
    }

    # 2. full referenced-GID atlas coverage — zero-coverage list fed into gate
    zero_coverage = sorted(g for g in referenced if g > V1_FROZEN_CEILING and g not in atlas_gids)
    gates["rq153c_full_referenced_gid_atlas_coverage"] = {
        "pass": len(zero_coverage) == 0,
        "zero_coverage_count": len(zero_coverage),
        "zero_coverage_gids": zero_coverage[:32],
        "atlas": V2_ATLAS.name,
    }

    # 3. renderability receipts — unrenderable list fed into gate
    unrenderable = sorted(
        g for g in referenced
        if g > V1_FROZEN_CEILING and not (g in rec_by_gid and rec_by_gid[g].get("rendered_bitmap_sha256"))
    )
    gates["rq153c_renderability_receipts"] = {
        "pass": len(unrenderable) == 0,
        "unrenderable_count": len(unrenderable),
        "unrenderable_gids": unrenderable[:32],
        "receipts": SHAPE_RECEIPTS.name,
    }

    # 4. shape-catalog measurement rows
    unmeasured = sorted(
        g for g in referenced
        if g > V1_FROZEN_CEILING and not (
            g in cat_by_gid and isinstance(cat_by_gid[g].get("shape6_norm"), list)
            and len(cat_by_gid[g]["shape6_norm"]) == 6
        )
    )
    gates["rq153c_shape_catalog_measurement_rows"] = {
        "pass": len(unmeasured) == 0,
        "unmeasured_count": len(unmeasured),
        "unmeasured_gids": unmeasured[:32],
        "catalog": V2_SHAPE_CATALOG.name,
    }

    # 5. candidate-floor (common cells only)
    thin = [c["key"] for c in cells["common"] if c["candidate_count"] < c["min_candidate_count"]]
    gates["rq153c_candidate_floor"] = {
        "pass": len(thin) == 0,
        "common_cells": len(cells["common"]),
        "rare_cells": len(cells["rare"]),
        "thin_cell_count": len(thin),
        "thin_cells": thin[:16],
    }

    # 6. runtime fail-marker contract
    #
    # A "fail marker" is what the renderer draws when it cannot honestly pick a
    # real glyph for a cell: a visible '!' in a reserved colour pair, carrying a
    # sentinel identity that is deliberately outside the renderable range. The
    # three failure kinds use three different reserved pairs so the reason is
    # readable off the screen.
    #
    # This gate checks the GENERATED receipt, which was produced by compiling
    # the engine and calling its marker producer. It does not check a document
    # anyone wrote by hand.
    marker_detail: dict[str, Any] = {
        "receipt": MARKER_CONTRACT.name,
        "exists": MARKER_CONTRACT.exists(),
        "generator": "scripts/generate_fl4131_profile_marker_contract.py",
    }
    marker_ok = False

    if MARKER_CONTRACT.exists():
        contract = load_json(MARKER_CONTRACT)
        markers = contract.get("markers", {})
        reserved_probe = contract.get("reserved_pair_probe", [])

        # Every required class present, each drawing the visible '!' and echoing
        # back the class it was asked for. A producer that returned a different
        # class than requested would be a real defect, so it is checked.
        classes_present = all(name in markers for name in REQUIRED_MARKER_CLASSES)
        glyph_is_bang = all(
            markers.get(name, {}).get("glyph_char") == "!"
            for name in REQUIRED_MARKER_CLASSES)
        class_echo_ok = all(
            markers.get(name, {}).get("marker_class_value")
            == markers.get(name, {}).get("marker_class_echoed")
            for name in REQUIRED_MARKER_CLASSES)

        # The three reserved colour pairs must be mutually distinct, otherwise
        # two different failure kinds would look identical on screen.
        pairs = [(markers.get(name, {}).get("fg"), markers.get(name, {}).get("bg"))
                 for name in REQUIRED_MARKER_CLASSES]
        pairs_distinct = len(set(pairs)) == len(pairs) and all(
            fg is not None and bg is not None for fg, bg in pairs)

        # The engine must agree those pairs are reserved, and must NOT claim an
        # ordinary pair is reserved. Both directions matter: the first stops a
        # real glyph from wearing marker colours, the second stops the guard
        # from rejecting legitimate palettes.
        reserved_lookup = {(row.get("fg"), row.get("bg")): row.get("engine_calls_reserved")
                           for row in reserved_probe}
        reserved_claimed = all(reserved_lookup.get(pair) is True for pair in pairs)
        negative_control = [row for row in reserved_probe
                            if (row.get("fg"), row.get("bg")) not in set(pairs)]
        negative_ok = bool(negative_control) and all(
            row.get("engine_calls_reserved") is False for row in negative_control)

        # The sentinel identity must sit outside the renderable content range,
        # so a marker can never be mistaken for a real glyph. The admission
        # module deliberately owns drawable CONTENT glyphs only and is not
        # consulted here.
        sentinel = contract.get("marker_sentinel_glyph_id")
        sentinel_ok = isinstance(sentinel, int) and sentinel > V1_FROZEN_CEILING

        marker_ok = all([classes_present, glyph_is_bang, class_echo_ok,
                         pairs_distinct, reserved_claimed, negative_ok, sentinel_ok])

        marker_detail.update({
            "marker_classes": sorted(markers),
            "all_required_classes_present": classes_present,
            "glyph_is_exclamation_for_all": glyph_is_bang,
            "producer_echoes_requested_class": class_echo_ok,
            "reserved_pairs_mutually_distinct": pairs_distinct,
            "engine_confirms_pairs_reserved": reserved_claimed,
            "ordinary_pair_not_reserved": negative_ok,
            "sentinel_glyph_id": sentinel,
            "sentinel_outside_content_range": sentinel_ok,
            "diagnostic": markers.get("FL4131_MARKER_DIAGNOSTIC"),
        })
    else:
        marker_detail["hint"] = (
            "run python3 scripts/generate_fl4131_profile_marker_contract.py")

    gates["rq153c_profile_marker_contract"] = {"pass": marker_ok, **marker_detail}

    # 7. the product actually runs and responds to input  (FL-4260, FL-4665)
    #
    # Fail-closed by construction. Every gate above can be green while the
    # editor is frozen, which is exactly what happened on 2026-08-03. This gate
    # exists so that state cannot be reported as PASS.
    gates["rq153c_runtime_accepts_input"] = check_runtime_interaction()

    mechanical_pass = all(g["pass"] for g in gates.values())

    # ── Operator residual (OBSERVATION ONLY — never affects mechanical verdict;
    #    Law 16 operator manual review owns this).
    #    The 72-primary review receipt set and its accepted/blocked state are owned by
    #    scripts/fl4260_review_receipts.py (Law 1: single owner of "the 72"). ──
    import fl4260_review_receipts as rq  # noqa: E402  (sibling front-door import)

    queue = rq.build_review_receipt_set()
    counts = rq.review_state(queue, rq.load_jsonl(MANUAL_RECEIPTS))
    table_runtime_profile_live = queue["table_runtime_profile_live"]

    observation = {
        "rq153c_manual_review_acceptance": {
            "kind": "operator_residual_observation",
            "note": "Per-cell human accept of the primary winner is operator-owned "
                    "(Law 16). The review apparatus (scripts/fl4260_review_receipts.py) "
                    "presents the 72 decisions and writes receipts; the mechanical "
                    "coverage gate passing is NOT closure. review_ready stays false "
                    "until every primary has a current accept receipt with no blocker.",
            "common_cell_primaries": queue["required_primary_count"],
            "primaries_with_accept_receipt": counts["accepted"],
            # Summed over the state vocabulary rather than a fixed list of names.
            # The hard-coded list named a review state that no longer exists, so
            # this gate raised KeyError instead of returning an evidence verdict
            # (FL-4260 / FL-4512).
            "primaries_without_accept_receipt": sum(
                count for state, count in counts.items()
                if state != rq.STATE_ACCEPTED
            ),
            "review_state_counts": counts,
            "table_runtime_profile_live": table_runtime_profile_live,
        }
    }

    result = {
        "fl": "FL-4260",
        "rq": "RQ-153c",
        "mechanical_coverage_verdict": "PASS" if mechanical_pass else "FAIL",
        "runtime_profile_live": table_runtime_profile_live,
        "closure": False,
        "closure_note": "Gates 1-6 are queries over files on disk: which glyph ids the tables "
                        "cite, whether they are in the atlas, whether they were measured, and "
                        "what the marker producer returns. They stay green while the product "
                        "itself is frozen, which is what happened on 2026-08-03 (FL-4665). "
                        "Gate 7 therefore requires evidence that the running product accepted a "
                        "movement input and a camera turn and changed what it drew. Even with "
                        "every gate green this is not closure: operator manual-review acceptance "
                        "(Law 16), final RQ-155 Trace refresh, canonical RQ-156, and Law 15 VPS "
                        "two-tab remain open.",
        "gates": gates,
        "observation": observation,
    }
    return result, (0 if mechanical_pass else 2)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    args = parser.parse_args()

    result, code = run_gate()

    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
        return code

    if result.get("verdict") == "INPUT_MISSING":
        print("RQ-153c coverage gate: INPUT MISSING")
        for m in result["missing"]:
            print(f"  - missing {m}")
        return code

    print("FL-4260 RQ-153c full referenced-GID coverage gate")
    print(f"  mechanical_coverage_verdict: {result['mechanical_coverage_verdict']}")
    print(f"  runtime_profile_live: {result['runtime_profile_live']}   closure: {result['closure']}")
    print("  gates:")
    for name, g in result["gates"].items():
        label = "PASS" if g["pass"] else "FAIL"
        extra = ""
        if "zero_coverage_count" in g:
            extra = f" zero_coverage={g['zero_coverage_count']}"
        elif "unrenderable_count" in g:
            extra = f" unrenderable={g['unrenderable_count']}"
        elif "unmeasured_count" in g:
            extra = f" unmeasured={g['unmeasured_count']}"
        elif "thin_cell_count" in g:
            extra = f" thin={g['thin_cell_count']} (common={g.get('common_cells')})"
        elif "referenced_total" in g:
            extra = f" total={g['referenced_total']} above{V1_FROZEN_CEILING}={g['referenced_above_ceiling']}"
        elif "glyph_byte" in g:
            extra = f" glyph={g.get('glyph_byte')} fg={g.get('fg')} bg={g.get('bg')}"
        print(f"    [{label}] {name}{extra}")
    obs = result["observation"]["rq153c_manual_review_acceptance"]
    print("  operator residual (NOT closure):")
    print(f"    manual-review primaries accepted: {obs['primaries_with_accept_receipt']}"
          f"/{obs['common_cell_primaries']}  (unaccepted={obs['primaries_without_accept_receipt']})")
    print(f"  {result['closure_note']}")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
