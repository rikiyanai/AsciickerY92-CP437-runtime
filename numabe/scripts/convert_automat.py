"""
convert_automat.py -- Converts a 3D binary auto-material lookup table to a 2D PNG strip.

ARCHITECTURE:
    The Asciicker terrain engine uses an "auto-material" lookup table to
    automatically assign materials to terrain cells based on their 3D
    neighborhood context. This table is authored or exported as a raw binary
    blob (auto_mat.bin) containing a 32x32x32 RGB voxel grid, and must be
    converted to a 2D PNG texture strip for import into the Godot rendering
    pipeline.

    The binary format stores 32 Z-slices of 32x32 RGB pixels, laid out
    sequentially. Each Z-slice is 32*32*3 = 3072 bytes, for a total of
    32*32*32*3 = 98304 bytes. The converter re-arranges these slices into
    a horizontal strip image: 1024 pixels wide (32 slices x 32 px) by 32
    pixels tall.

KEY EXPORTS:
    convert_bin_to_png(bin_path, png_path) -- Core conversion function.
    main()                                  -- CLI entry point.

PIPELINE CONTEXT:
    Upstream: auto_mat.bin is generated by the terrain/material authoring
    tools or exported from the C++ engine's terrain system (terrain.cpp).
    Downstream: auto_mat.png is loaded by the Godot project's terrain
    shader as a texture lookup table for automatic material assignment.

    [DATA-CONTRACT:AUTOMAT-BIN] -- Input: raw RGB binary blob,
        exactly 98304 bytes = 32x32x32 voxels x 3 bytes/pixel.
        No header, no compression, no padding.
    [DEPENDENCY:PIL] -- Uses Pillow for raw-byte-to-image conversion and PNG save.
"""

from PIL import Image
import sys
import os
import argparse


def convert_bin_to_png(bin_path, png_path):
    """
    Convert a 3D auto-material binary lookup table to a 2D PNG strip image.

    The binary file encodes a 32x32x32 RGB voxel grid as raw bytes. This
    function slices it along the Z axis into 32 separate 32x32 images and
    arranges them side-by-side into a 1024x32 horizontal strip PNG.

    [DATA-CONTRACT:AUTOMAT-BIN] Input must be exactly 98304 bytes.
    [DEPENDENCY:PIL] Uses PIL.Image.frombytes for raw data decoding.

    Args:
        bin_path: Path to the input .bin file (32x32x32x3 raw RGB).
        png_path: Path for the output .png strip image (1024x32).

    Returns:
        True on success, False on error (with diagnostic printed to stdout).

    Raises:
        No exceptions propagate; all errors are caught internally and
        result in a False return with diagnostic output to stdout.
    """
    try:
        if not os.path.exists(bin_path):
            print(f"Error: Input file not found: {bin_path}")
            return False

        with open(bin_path, 'rb') as f:
            data = f.read()

        # WHY 98304: 32 * 32 * 32 voxels * 3 bytes (R,G,B) per voxel.
        # Any deviation means the file is corrupt or uses a different grid size.
        expected_size = 98304
        if len(data) != expected_size:
            print(f"Error: Unexpected file size {len(data)}. Expected {expected_size}.")
            return False

        # WHY 1024x32: 32 Z-slices of 32px each = 1024px wide, 32px tall.
        # This horizontal strip layout matches what the Godot terrain shader
        # expects when sampling the auto-material LUT by (x, y, z) coordinates
        # remapped to (z*32 + x, y) in texture space.
        strip_img = Image.new('RGB', (1024, 32))

        # Size of one Z-slice in bytes: 32 width * 32 height * 3 bytes/pixel
        slice_size = 3072

        for z in range(32):
            # Extract raw bytes for this Z-slice
            start = z * slice_size
            end = start + slice_size
            slice_bytes = data[start:end]

            # WHY frombytes: The binary data is already in packed RGB format
            # with no header or padding, which matches PIL's raw "RGB" mode exactly.
            slice_img = Image.frombytes('RGB', (32, 32), slice_bytes)

            # Paste into the strip at horizontal offset z * 32
            strip_img.paste(slice_img, (z * 32, 0))

        strip_img.save(png_path)
        print(f"Successfully converted {bin_path} to {png_path} (Correctly Stripped)")
        return True

    except Exception as e:
        print(f"Error: {e}")
        return False


def main():
    """
    CLI entry point. Parses arguments and runs the bin-to-png conversion.

    Default paths point to the Godot project's asset directory, which is the
    standard location for auto-material data in the Asciicker project tree.

    Returns:
        Exits with code 0 on success, 1 on failure.
    """
    parser = argparse.ArgumentParser(description="Convert 3D binary lookup table to 2D PNG strip.")
    # TODO(PIPELINE-FIX): Hardcoded default paths assume CWD is project root.
    # If invoked from a different directory, these defaults will silently fail.
    parser.add_argument("input", nargs="?", default="godot_project/assets/auto_mat.bin", help="Input binary file path")
    parser.add_argument("output", nargs="?", default="godot_project/assets/auto_mat.png", help="Output PNG file path")

    args = parser.parse_args()

    success = convert_bin_to_png(args.input, args.output)
    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()